// 將一條邊拆成「直線段 + 45° 斜段」，模擬捷運路線圖的折角畫法
export function elbow(a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const adx = Math.abs(dx), ady = Math.abs(dy);
  if (adx === 0 || ady === 0 || adx === ady) return [a, b]; // 已是 0/45/90 度
  const sx = Math.sign(dx), sy = Math.sign(dy);
  // 較長的軸先走直線，剩下的距離用 45° 斜線收尾
  const mid = adx > ady
    ? [a[0] + sx * (adx - ady), a[1]]
    : [a[0], a[1] + sy * (ady - adx)];
  return [a, mid, b];
}
